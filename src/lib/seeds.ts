/** Builds an unclaimed, distinctly styled building on any market plot. */
export function createMarketBuilding(plot: Plot, indexInDistrict: number): Store {
  const code = plot.id.split('-')[0];
  const catData = DISTRICT_CATALOG[code];
  const idx = indexInDistrict % (catData?.names.length || 56);
  const [name, tagline] = catData?.names[idx] || [`${plot.district} Studio ${indexInDistrict + 1}`, `Premier location on Plot ${plot.id}`];

  const tpls = catData?.templates || ['office', 'tech', 'boutique', 'cafe'];
  const template = tpls[idx % tpls.length];

  const facades = catData?.facades || ['concrete', 'brick', 'stone', 'wood', 'metal'];
  const facade = facades[idx % facades.length];

  const tints = catData?.tints || ['#ffffff', '#f0d9bf', '#e8c9c9', '#cfe0cf', '#c9d6e4', '#d8cfe6'];
  const tint = tints[idx % tints.length];

  const themes = catData?.themes || ['#3b82f6', '#10b981', '#f59e0b', '#8b5cf6'];
  const theme = themes[idx % themes.length];

  const roofs = catData?.roofs || ['flat', 'cornice', 'gabled', 'sloped'];
  const roof = roofs[idx % roofs.length];

  const signs = catData?.signs || ['panel', 'neon', 'box', 'blade'];
  const sign = signs[idx % signs.length];

  const windowsList = ['grid', 'ribbon', 'tall'];
  const windows = windowsList[idx % windowsList.length];

  const doorsList = ['glass', 'wood', 'steel'];
  const door = doorsList[idx % doorsList.length];

  const glassList = ['clear', 'blue', 'tinted', 'frosted'];
  const glass = glassList[idx % glassList.length];

  const awningsList = ['none', 'striped', 'solid', 'canopy'];
  const awning = awningsList[idx % awningsList.length];

  // Height variation: corners and featured plots are taller
  const floors = (plot.tier === 'corner' || plot.tier === 'featured' || idx % 4 === 0) ? Math.min(4, Math.max(2, 4 - (idx % 2))) : Math.max(1, (idx % 3) + 1);

  const balcony = floors > 1 && (idx % 3 === 1);
  const planters = idx % 2 === 0;
  const trim = true;

  const website = `https://${name.toLowerCase().replace(/[^a-z0-9]/g, '')}.local`;

  return {
    plotId: plot.id,
    ownerId: null,
    visits: 0,
    clicks: 0,
    config: defaultConfig(template, {
      name,
      tagline,
      website,
      theme,
      facade,
      tint,
      glass,
      windows,
      door,
      roof,
      awning,
      sign,
      floors,
      balcony,
      planters,
      trim,
      lights: true,
      place: { ox: 0, oz: 0.8, rot: 0 },
    }),
  };
}

